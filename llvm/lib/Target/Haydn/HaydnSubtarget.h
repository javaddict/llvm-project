#define GET_SUBTARGETINFO_HEADER
#include "HaydnGenSubtargetInfo.inc"

namespace llvm {

class HaydnSubtarget : public HaydnGenSubtargetInfo {
  virtual void anchor();

  HaydnFrameLowering FrameLowering;
  HaydnInstrInfo InstrInfo;
  HaydnTargetLowering TLInfo;
  InstrItineraryData ItinData;

  // GlobalISel objects
  std::unique_ptr<CallLowering> CallLoweringInfo;
  std::unique_ptr<InlineAsmLowering> InlineAsmLoweringInfo;
  std::unique_ptr<LegalizerInfo> Legalizer;
  std::unique_ptr<RegisterBankInfo> RegBankInfo;
  std::unique_ptr<InstructionSelector> InstSelector;

  // Feature flags
  bool HasAGU;
  bool HasCircularBuffer;
  bool HasBitReversed;
  bool HasHWLoop;
  bool HasSIMD;
  // mattr=+frame-pointer — force R14 FP (default false; still ABI-required).
  bool UseFramePointer;

  // Immutable object-encoding profile for this subtarget (production E96).
  // Resolved once from the target machine; never inferred from byte width.
  haydn::format::ObjectEncodingProfileID EncodingProfile =
      haydn::format::ObjectEncodingProfileID::E96;

public:
  HaydnSubtarget(const Triple &TT, StringRef CPU, StringRef TuneCPU,
                StringRef FS, const TargetMachine &TM);

  ~HaydnSubtarget() override;

  const HaydnFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const HaydnInstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const HaydnRegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }
  const HaydnTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const InstrItineraryData *getInstrItineraryData() const override {
    return &ItinData;
  }

  // Initializes using the passed in CPU and feature strings so that we can
  // use initializer lists for subtarget initialization.
  HaydnSubtarget &initializeSubtargetDependencies(const Triple &TT,
                                                 StringRef CPU,
                                                 StringRef TuneCPU,
                                                 StringRef FS);

  // Generated by inc file
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  bool hasAGU() const { return HasAGU; }
  bool hasCircularBuffer() const { return HasCircularBuffer; }
  bool hasBitReversed() const { return HasBitReversed; }
  bool hasHWLoop() const { return HasHWLoop; }
  bool hasSIMD() const { return HasSIMD; }

  // True when a dedicated FP is forced (-mattr=+frame-pointer).
  bool useFramePointer() const { return UseFramePointer; }

  /// Production ObjectEncodingProfile for this subtarget (always E96 today).
  haydn::format::ObjectEncodingProfileID getObjectEncodingProfileID() const {
    return EncodingProfile;
  }

  /// Descriptor for the subtarget's object-encoding profile.
  const haydn::format::ObjectEncodingProfileDesc &
  getObjectEncodingProfile() const {
    const haydn::format::ObjectEncodingProfileDesc *P =
        haydn::format::getObjectEncodingProfile(EncodingProfile);
    assert(P && "subtarget encoding profile missing from registry");
    return *P;
  }

  // AIE2 dual-scheduler gates.
  // Both pre-RA MachineScheduler and post-RA PostMachineScheduler are ON.
  // createMachineScheduler returns HaydnPreRASchedStrategy (never nullptr).
  bool enableMachineScheduler() const override { return true; }

  // Explicit override (AIE2Subtarget pattern) so post-RA does not depend solely
  // on the default AND of enableMachineScheduler && enablePostRAScheduler.
  bool enablePostRAMachineScheduler() const override { return true; }

  // Track register pressure even in small regions (AIE / RISCV pattern).
  // Stock LLVM signature uses SchedRegion (not bare NumRegionInstrs).
  void overrideSchedPolicy(MachineSchedPolicy &Policy,
                           const SchedRegion &Region) const override;

  // Post-RA: keep pressure tracking off (physregs); leave direction default.
  void overridePostRASchedPolicy(MachineSchedPolicy &Policy,
                                 const SchedRegion &Region) const override;

  // Enable generic SSA EarlyIfConversion (speculate + insertSelect → MOVT/MOVF).
  // Preferred over post-RA GenMux Pattern 2 (Hexagon/AIE-style). See
  // plans/archive/2026-08-13-d490/DECISION-D490-early-ifconv-retire-genmux.md.
  bool enableEarlyIfConversion() const override { return true; }

  // The WindowScheduler (upstream's newer SMS fallback) crashes on
  // ZOL-form loops because its TripleMBB cloning doesn't handle the
  // PseudoLoopEnd meta-terminator correctly. The SwingModuloScheduler
  // (the original SMS) handles ZOL loops fine via PipelinerLoopInfo. When
  // ZOL pipelining is enabled, disable the WindowScheduler so only the
  // SwingModuloScheduler runs.
  bool enableWindowScheduler() const override;
  // Target-specific adjustment of a schedule dependency's latency.
  // SMS (MachinePipeliner.cpp:1271/1302) hard-codes the loop-carried
  // MAC->PHI anti edge to latency 1 and the PHI->MAC data edge to latency 0
  // then calls this hook to let the target rewrite them. Without an override
  // the SMS recurrence MII for a MAC accumulator loop is always 1+0 = 1
  // *regardless* of the itinerary — so per-operand OperandCycles never reach
  // the recurrence computation. Hexagon has the same issue and overrides
  // this hook (HexagonSubtarget.cpp:434). This override recomputes the
  // latency from the itinerary via TargetInstrInfo::getOperandLatency, so
  // MAC's asymmetric [2,1,1,2] operand cycles flow through: the acc->acc
  // feedback edge is latency 1 (formula 2-2+1) and the result->other edge
  // is latency 2 (2-1+1). See D2XX. Only data/anti edges between
  // real MIs with known operand indices are rewritten; everything else
  // keeps the upstream default.
  void adjustSchedDependency(SUnit *Def, int DefOpIdx, SUnit *Use, int UseOpIdx,
                             SDep &Dep,
                             const TargetSchedModel *SchedModel) const override;

  // GlobalISel getters
  const CallLowering *getCallLowering() const override {
    return CallLoweringInfo.get();
  }
  // empty side-effecting inline asm (`asm volatile("" ::: "memory")`)
  // crashed IRTranslator with "Inline asm lowering is not supported". Wire the
  // generic InlineAsmLowering (AArch64 pattern) so memory-barrier / empty asm
  // lower to INLINEASM without a fatal backend error.
  const InlineAsmLowering *getInlineAsmLowering() const override {
    return InlineAsmLoweringInfo.get();
  }
  const LegalizerInfo *getLegalizerInfo() const override {
    return Legalizer.get();
  }
  const RegisterBankInfo *getRegBankInfo() const override {
    return RegBankInfo.get();
  }
  InstructionSelector *getInstructionSelector() const override {
    return InstSelector.get();
  }
  // PostLegalizerCombiner not implemented for M0 - uses base class default

  static constexpr unsigned XLen = 32;

  // Override libcall lowering to use standard compiler-rt functions
  void initLibcallLoweringInfo(class LibcallLoweringInfo &Info) const override;
};

} // namespace llvm

#endif // LLVM_LIB_TARGET_HAYDN_HAYDNSUBTARGET_H
