#!/usr/bin/env python3
"""Emit HaydnGenAltOccupancy.inc from CodeGenFormat AlternateInsts.

Occupancy is residual LogicalMaterialize / MultiSlot_Pseudo holes
(index == SLOT bit). Opcode IDs in Fallback[] are residual occupancy opcodes used only
when no Format E member exists at that residual index. Do not derive
Mask from Format E EntryIdx (ADD64/X4CMUL16/LD32 would gain e0/e2).

  python3 generate_alt_occupancy.py \\
      --formats /ssd2/mhyang/haydn-build/lib/Target/Haydn/HaydnGenFormats.inc \\
      --out ../HaydnGenAltOccupancy.inc
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

ARRAY_RE = re.compile(
    r"// Haydn::(\w+) \((?:LogicalMaterialize|MultiSlot_Pseudo)[^)]*\)[^\n]*\n"
    r"\s*\{\s*([^}]+)\}",
    re.M,
)
CASE_RE = re.compile(
    r"case Haydn::(\w+):\s*\n\s*return &AlternateInsts\[(\d+)\];",
    re.M,
)


def parse_members(body: str) -> list[str]:
    parts = [p.strip() for p in body.split(",")]
    if len(parts) != 3:
        raise SystemExit(f"expected 3 members, got {parts!r}")
    return parts


def mask_of(members: list[str]) -> int:
    bits = 0
    for i, m in enumerate(members):
        if m != "0":
            bits |= 1 << i
    return bits


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--formats", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    text = args.formats.read_text()
    start = text.find("static std::vector<unsigned int> const AlternateInsts[]")
    if start < 0:
        raise SystemExit("AlternateInsts table not found")
    func = text.find("HaydnMCFormats::getAlternateInstsOpcode", start)
    if func < 0:
        raise SystemExit("getAlternateInstsOpcode not found")
    table = text[start:func]
    switch = text[func : text.find("#endif // GET_ALTERNATE_INST_OPCODE_FUNC", func)]

    rows: list[tuple[str, list[str]]] = []
    for m in ARRAY_RE.finditer(table):
        rows.append((m.group(1), parse_members(m.group(2))))
    cases = [(m.group(1), int(m.group(2))) for m in CASE_RE.finditer(switch)]
    if not rows or not cases:
        raise SystemExit(f"parse failed: rows={len(rows)} cases={len(cases)}")
    if len(rows) != len(cases):
        raise SystemExit(f"row/case mismatch: {len(rows)} vs {len(cases)}")
    for name, idx in cases:
        if idx >= len(rows):
            raise SystemExit(f"{name} index {idx} out of range")
        if rows[idx][0] != name:
            raise SystemExit(f"{name} comment is {rows[idx][0]}")

    lines = [
        "//===-- HaydnGenAltOccupancy.inc -*- C++ -*-===//",
        "// Generated by FormatE/generate_alt_occupancy.py from",
        "// HaydnGenFormats.inc AlternateInsts (LogicalMaterialize +",
        "// MultiSlot_Pseudo holes). DO NOT EDIT.",
        "// Mask bit i = residual occupancy class i (SLOT0/1/2).",
        "// Fallback[i] is the residual occupancy opcode, or 0 for a hole.",
        "#ifdef GET_HAYDN_ALT_OCCUPANCY",
        "#undef GET_HAYDN_ALT_OCCUPANCY",
        "",
        "struct HaydnAltOccupancyRow {",
        "  unsigned LogicalOpc;",
        "  uint8_t Mask;",
        "  unsigned Fallback[3];",
        "};",
        "",
        "static const HaydnAltOccupancyRow HaydnAltOccupancy[] = {",
    ]
    for name, members in rows:
        mask = mask_of(members)
        lines.append(
            f"    {{ Haydn::{name}, {mask:#x}, "
            f"{{ {members[0]}, {members[1]}, {members[2]} }} }},"
        )
    lines.append("};")
    lines.append("")
    lines.append("static int haydnAltOccupancyIndex(unsigned Opcode) {")
    lines.append("  switch (Opcode) {")
    lines.append("  default:")
    lines.append("    return -1;")
    for i, (name, _) in enumerate(rows):
        lines.append(f"  case Haydn::{name}:")
        lines.append(f"    return {i};")
    lines.append("  }")
    lines.append("}")
    lines.append("#endif // GET_HAYDN_ALT_OCCUPANCY")
    lines.append("")
    args.out.write_text("\n".join(lines))
    print(f"wrote {args.out} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
